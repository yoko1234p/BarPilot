    }
}

public enum ClipboardHistoryPolicy {
    public static let maxEntryBytes = 5 * 1024 * 1024
    public static let maxTotalBytes = 20 * 1024 * 1024
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard",
    ]
    public static func mayCollect(types: [String]) -> Bool {
        !types.contains { concealedTypes.contains($0) }
    }
    public static func prune(_ entries: [ClipboardEntry], now: Date, days: Int, limit: Int) -> [ClipboardEntry] {
        let cutoff = now.addingTimeInterval(-Double(max(1, min(days, 90))) * 86400)
        let sorted = entries.filter { ($0.pinned || $0.copiedAt >= cutoff) && $0.data.count <= maxEntryBytes }
            .sorted { $0.pinned == $1.pinned ? $0.copiedAt > $1.copiedAt : $0.pinned }
        var digests = Set<String>(); var bytes = 0
        var result: [ClipboardEntry] = []
        for entry in sorted {
            guard result.count < max(1, min(limit, 500)), !digests.contains(entry.digest),
                bytes + entry.data.count <= maxTotalBytes else { continue }
            result.append(entry); digests.insert(entry.digest); bytes += entry.data.count
        }
        return result
    }
}

public struct WeatherLocation: Codable, Equatable {
    public var name: String
    public var latitude: Double
    public var longitude: Double
    public init(name: String, latitude: Double, longitude: Double) {
        self.name = name; self.latitude = latitude; self.longitude = longitude
    }
    public var isValid: Bool {
        latitude.isFinite && longitude.isFinite && (-90...90).contains(latitude) && (-180...180).contains(longitude)
    }
    public var requestURL: URL? {
        guard isValid else { return nil }
        var components = URLComponents(string: "https://api.open-meteo.com/v1/forecast")!
        components.queryItems = [
            URLQueryItem(name: "latitude", value: String(latitude)),
            URLQueryItem(name: "longitude", value: String(longitude)),
            URLQueryItem(name: "current", value: "temperature_2m,apparent_temperature,weather_code,is_day,wind_speed_10m"),
            URLQueryItem(name: "daily", value: "temperature_2m_max,temperature_2m_min,precipitation_probability_max"),
            URLQueryItem(name: "forecast_days", value: "1"),
            URLQueryItem(name: "timezone", value: "auto"),
        ]
        return components.url
    }
}

public enum MeetingLink {
    /// Only links in the event's URL/location/notes are considered; no guessed meeting IDs.
    public static func first(in fields: [String]) -> URL? {
        let detector = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue)
        for field in fields {
            let range = NSRange(field.startIndex..<field.endIndex, in: field)
            for match in detector?.matches(in: field, range: range) ?? [] {
                guard let url = match.url, url.scheme?.lowercased() == "https", let host = url.host?.lowercased() else { continue }
                let providers = ["zoom.us", "meet.google.com", "teams.microsoft.com", "teams.live.com", "webex.com"]
                if providers.contains(where: { host == $0 || host.hasSuffix("." + $0) }) { return url }
            }
        }
        return nil
    }
}

public struct AgentQuota: Equatable, Identifiable {
    public var id: String
    public var percent: Double
    public var resetAt: Date?
    public init?(id: String, percent: Double, resetAt: Double?) {
        guard percent.isFinite, (0...100).contains(percent) else { return nil }
        self.id = String(id.prefix(120)); self.percent = percent
        self.resetAt = resetAt.flatMap { $0.isFinite ? Date(timeIntervalSince1970: $0) : nil }
    }
}

public enum AgentSnapshotReader {
    public struct Snapshot: Equatable {
        public var provider: String
        public var quotas: [AgentQuota]
        public var updatedAt: Date?
        public var isStale: Bool
    }
    /// Extract numeric metadata only. Intentionally does not expose prompts, sessions, source paths or status text.
    public static func read(_ data: Data, now: Date) -> [Snapshot] {
        guard data.count <= 1024 * 1024,
            let objects = try? JSONSerialization.jsonObject(with: data) as? [[String: Any]] else { return [] }
        return objects.compactMap { object in
            guard let provider = object["provider"] as? String, ["codex", "claude"].contains(provider) else { return nil }
            let timestamp = number(object["updatedAt"])
            let updated = timestamp.flatMap { $0.isFinite ? Date(timeIntervalSince1970: $0) : nil }
            let quotas = (object["windows"] as? [[String: Any]] ?? []).compactMap { value -> AgentQuota? in
                guard let id = value["id"] as? String, let percent = number(value["percent"]) else { return nil }
                return AgentQuota(id: id, percent: percent, resetAt: number(value["resetsAt"]))
            }
            let stale = object["unavailable"] as? Bool == true || (updated.map { now.timeIntervalSince($0) > 1200 || $0 > now.addingTimeInterval(60) } ?? true)
            return Snapshot(provider: provider, quotas: quotas, updatedAt: updated, isStale: stale)
        }
    }
    private static func number(_ value: Any?) -> Double? {
        guard let value = value as? NSNumber, CFGetTypeID(value) != CFBooleanGetTypeID() else { return nil }
        return value.doubleValue.isFinite ? value.doubleValue : nil
    }
}
